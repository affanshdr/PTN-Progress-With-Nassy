-- 8a. Beli / Perpanjang Live Class Pass 30 Hari (100 Coin)
create or replace function public.purchase_liveclass_pass()
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_uid uuid := auth.uid();
  v_cost constant integer := 100;
  v_profile public.profiles%rowtype;
  v_new_balance integer;
  v_new_until timestamptz;
begin
  if v_uid is null then
    raise exception 'Silakan login terlebih dahulu.';
  end if;

  select * into v_profile
  from public.profiles
  where id = v_uid
  for update;

  if not found then
    raise exception 'Profil pengguna tidak ditemukan.';
  end if;

  if v_profile.coin_balance < v_cost then
    raise exception 'Saldo coin tidak mencukupi. Dibutuhkan % coin untuk akses Live Class 30 hari.', v_cost;
  end if;

  v_new_balance := v_profile.coin_balance - v_cost;
  v_new_until := greatest(coalesce(v_profile.liveclass_pass_until, now()), now()) + interval '30 days';

  perform set_config('app.allow_wallet_mutation', 'on', true);

  update public.profiles
  set coin_balance = v_new_balance,
      liveclass_pass_until = v_new_until
  where id = v_uid;

  insert into public.coin_transactions (
    user_id,
    amount,
    type,
    title,
    reference_id,
    balance_after
  )
  values (
    v_uid,
    -v_cost,
    'liveclass_pass',
    'Aktifkan Live Class Pass 30 Hari',
    to_char(v_new_until at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
    v_new_balance
  );

  return jsonb_build_object(
    'coin_balance', v_new_balance,
    'liveclass_pass_until', v_new_until
  );
end;
$$;

-- 8b. Daftar / Unlock Tryout Mingguan (Default 25 Coin)
create or replace function public.unlock_tryout(p_tryout_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_uid uuid := auth.uid();
  v_tryout public.tryouts%rowtype;
  v_profile public.profiles%rowtype;
  v_new_balance integer;
begin
  if v_uid is null then
    raise exception 'Silakan login terlebih dahulu.';
  end if;

  select * into v_tryout
  from public.tryouts
  where id = p_tryout_id
    and is_published = true;

  if not found then
    raise exception 'Paket tryout tidak ditemukan.';
  end if;

  if v_tryout.ends_at < now() then
    raise exception 'Periode pendaftaran tryout ini sudah berakhir.';
  end if;

  if exists (
    select 1
    from public.tryout_registrations
    where tryout_id = p_tryout_id
      and user_id = v_uid
  ) then
    select coin_balance into v_new_balance
    from public.profiles
    where id = v_uid;

    return jsonb_build_object(
      'coin_balance', v_new_balance,
      'already_unlocked', true,
      'coins_paid', 0
    );
  end if;

  select * into v_profile
  from public.profiles
  where id = v_uid
  for update;

  if not found then
    raise exception 'Profil pengguna tidak ditemukan.';
  end if;

  if v_profile.coin_balance < v_tryout.coin_cost then
    raise exception 'Saldo coin tidak cukup. Butuh % coin untuk membuka tryout ini.', v_tryout.coin_cost;
  end if;

  v_new_balance := v_profile.coin_balance - v_tryout.coin_cost;

  perform set_config('app.allow_wallet_mutation', 'on', true);

  update public.profiles
  set coin_balance = v_new_balance
  where id = v_uid;

  insert into public.tryout_registrations (tryout_id, user_id, coins_paid)
  values (p_tryout_id, v_uid, v_tryout.coin_cost);

  if v_tryout.coin_cost > 0 then
    insert into public.coin_transactions (
      user_id,
      amount,
      type,
      title,
      reference_id,
      balance_after
    )
    values (
      v_uid,
      -v_tryout.coin_cost,
      'tryout_unlock',
      'Daftar ' || v_tryout.title,
      p_tryout_id::text,
      v_new_balance
    );
  end if;

  return jsonb_build_object(
    'coin_balance', v_new_balance,
    'already_unlocked', false,
    'coins_paid', v_tryout.coin_cost
  );
end;
$$;

-- 8c. Katalog Tryout untuk User (beserta jumlah soal, status daftar, & skor user)
create or replace function public.get_tryout_catalog()
returns table (
  id uuid,
  slug text,
  week_number integer,
  title text,
  description text,
  coin_cost integer,
  duration_minutes integer,
  starts_at timestamptz,
  ends_at timestamptz,
  question_count integer,
  participant_count integer,
  is_registered boolean,
  has_attempted boolean,
  user_score integer,
  user_correct_count integer
)
language sql
security definer
set search_path = public, auth
as $$
  select
    t.id,
    t.slug,
    t.week_number,
    t.title,
    t.description,
    t.coin_cost,
    t.duration_minutes,
    t.starts_at,
    t.ends_at,
    coalesce((select count(*)::integer from public.tryout_questions q where q.tryout_id = t.id), 0) as question_count,
    coalesce((select count(*)::integer from public.tryout_attempts a where a.tryout_id = t.id), 0) as participant_count,
    exists(
      select 1 from public.tryout_registrations r
      where r.tryout_id = t.id and r.user_id = auth.uid()
    ) as is_registered,
    exists(
      select 1 from public.tryout_attempts a
      where a.tryout_id = t.id and a.user_id = auth.uid()
    ) as has_attempted,
    (
      select a.score from public.tryout_attempts a
      where a.tryout_id = t.id and a.user_id = auth.uid()
      limit 1
    ) as user_score,
    (
      select a.correct_count from public.tryout_attempts a
      where a.tryout_id = t.id and a.user_id = auth.uid()
      limit 1
    ) as user_correct_count
  from public.tryouts t
  where t.is_published = true
  order by t.week_number asc, t.starts_at asc;
$$;

-- 8d. Ambil Soal Tryout (Hanya jika terdaftar & tanpa kunci jawaban/pembahasan)
create or replace function public.get_tryout_questions(p_tryout_id uuid)
returns table (
  id uuid,
  subtest text,
  question_order integer,
  question_text text,
  option_a text,
  option_b text,
  option_c text,
  option_d text,
  option_e text
)
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_uid uuid := auth.uid();
  v_tryout public.tryouts%rowtype;
begin
  if v_uid is null then
    raise exception 'Silakan login terlebih dahulu.';
  end if;

  select * into v_tryout
  from public.tryouts
  where tryouts.id = p_tryout_id
    and tryouts.is_published = true;

  if not found then
    raise exception 'Paket tryout tidak ditemukan.';
  end if;

  if not exists (
    select 1
    from public.tryout_registrations r
    where r.tryout_id = p_tryout_id
      and r.user_id = v_uid
  ) then
    raise exception 'Kamu belum mendaftar tryout ini.';
  end if;

  if v_tryout.starts_at > now() then
    raise exception 'Tryout ini belum dibuka sesuai jadwal.';
  end if;

  return query
  select
    q.id,
    q.subtest,
    q.question_order,
    q.question_text,
    q.option_a,
    q.option_b,
    q.option_c,
    q.option_d,
    q.option_e
  from public.tryout_questions q
  where q.tryout_id = p_tryout_id
  order by q.question_order asc;
end;
$$;

-- 8e. Submit Jawaban Tryout + Hitung Skor Skala 200-1000 di Server
create or replace function public.submit_tryout_attempt(
  p_tryout_id uuid,
  p_answers jsonb,
  p_duration_seconds integer default 0
)
returns public.tryout_attempts
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_uid uuid := auth.uid();
  v_existing public.tryout_attempts%rowtype;
  v_q record;
  v_selected text;
  v_is_correct boolean;
  v_total integer := 0;
  v_correct integer := 0;
  v_score integer := 0;
  v_breakdown jsonb := '{}'::jsonb;
  v_sub_obj jsonb;
  v_sub_total integer;
  v_sub_correct integer;
  v_inserted public.tryout_attempts%rowtype;
begin
  if v_uid is null then
    raise exception 'Silakan login terlebih dahulu.';
  end if;

  if not exists (
    select 1
    from public.tryout_registrations
    where tryout_id = p_tryout_id
      and user_id = v_uid
  ) then
    raise exception 'Kamu belum terdaftar pada tryout ini.';
  end if;

  select * into v_existing
  from public.tryout_attempts
  where tryout_id = p_tryout_id
    and user_id = v_uid;

  if found then
    return v_existing;
  end if;

  for v_q in
    select id, subtest, correct_option
    from public.tryout_questions
    where tryout_id = p_tryout_id
    order by question_order asc
  loop
    v_total := v_total + 1;
    v_selected := upper(coalesce(p_answers ->> v_q.id::text, ''));
    v_is_correct := (v_selected = v_q.correct_option);

    if v_is_correct then
      v_correct := v_correct + 1;
    end if;

    v_sub_obj := coalesce(v_breakdown -> v_q.subtest, '{"correct":0,"total":0}'::jsonb);
    v_sub_total := coalesce((v_sub_obj ->> 'total')::integer, 0) + 1;
    v_sub_correct := coalesce((v_sub_obj ->> 'correct')::integer, 0) + case when v_is_correct then 1 else 0 end;

    v_breakdown := jsonb_set(
      v_breakdown,
      array[v_q.subtest],
      jsonb_build_object('correct', v_sub_correct, 'total', v_sub_total),
      true
    );
  end loop;

  if v_total > 0 then
    v_score := round(200 + (v_correct::numeric / v_total::numeric) * 800)::integer;
  else
    v_score := 0;
  end if;

  insert into public.tryout_attempts (
    tryout_id,
    user_id,
    answers,
    correct_count,
    total_questions,
    score,
    subtest_breakdown,
    duration_seconds
  )
  values (
    p_tryout_id,
    v_uid,
    coalesce(p_answers, '{}'::jsonb),
    v_correct,
    v_total,
    v_score,
    v_breakdown,
    greatest(coalesce(p_duration_seconds, 0), 0)
  )
  returning * into v_inserted;

  return v_inserted;
end;
$$;


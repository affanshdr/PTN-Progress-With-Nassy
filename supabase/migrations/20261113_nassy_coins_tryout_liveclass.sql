do $$
declare
  v_profile record;
begin
  perform set_config('app.allow_wallet_mutation', 'on', true);

  for v_profile in
    select p.id, p.coin_balance
    from public.profiles p
    where not exists (
      select 1
      from public.coin_transactions ct
      where ct.user_id = p.id
        and ct.type = 'welcome_bonus'
    )
  loop
    if coalesce(v_profile.coin_balance, 0) < 100 then
      update public.profiles
      set coin_balance = 100
      where id = v_profile.id;
    end if;

    insert into public.coin_transactions (
      user_id,
      amount,
      type,
      title,
      reference_id,
      balance_after
    )
    values (
      v_profile.id,
      100,
      'welcome_bonus',
      'Bonus Selamat Datang Akun Baru',
      v_profile.id::text,
      greatest(coalesce(v_profile.coin_balance, 100), 100)
    );
  end loop;
end $$;

-- ----------------------------------------------------------------------------
-- 3. Trigger Keamanan Wallet & Bonus Coin Otomatis untuk Akun Baru (100 Coin)
-- ----------------------------------------------------------------------------
create or replace function public.guard_profile_wallet_columns()
returns trigger
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_allow_mutation boolean;
begin
  v_allow_mutation :=
    current_setting('app.allow_wallet_mutation', true) = 'on'
    or coalesce(auth.role(), '') = 'service_role'
    or current_user in ('postgres', 'supabase_admin');

  if tg_op = 'INSERT' then
    if not v_allow_mutation then
      new.coin_balance := 100;
      new.liveclass_pass_until := null;
    else
      new.coin_balance := coalesce(new.coin_balance, 100);
    end if;
    return new;
  end if;

  if tg_op = 'UPDATE' then
    if (
      new.coin_balance is distinct from old.coin_balance
      or new.liveclass_pass_until is distinct from old.liveclass_pass_until
    ) and not v_allow_mutation then
      raise exception 'Perubahan saldo coin atau masa aktif Live Class hanya boleh dilakukan melalui transaksi resmi sistem.';
    end if;
    return new;
  end if;

  return new;
end;
$$;

drop trigger if exists trg_guard_profile_wallet_columns on public.profiles;
create trigger trg_guard_profile_wallet_columns
  before insert or update on public.profiles
  for each row
  execute function public.guard_profile_wallet_columns();


create or replace function public.get_tryout_leaderboard(p_tryout_id uuid default null)
returns table (
  user_id uuid,
  name text,
  ptn text,
  class_name text,
  score integer,
  best_score integer,
  correct_count integer,
  total_questions integer,
  duration_seconds integer,
  attempts_count integer,
  submitted_at timestamptz
)
language sql
security definer
set search_path = public, auth
as $$
  with per_event as (
    select
      a.user_id,
      p.name,
      p.ptn,
      p.class_name,
      a.score,
      a.score as best_score,
      a.correct_count,
      a.total_questions,
      a.duration_seconds,
      1::integer as attempts_count,
      a.submitted_at
    from public.tryout_attempts a
    join public.profiles p on p.id = a.user_id
    where p_tryout_id is not null
      and a.tryout_id = p_tryout_id
  ),
  overall as (
    select
      a.user_id,
      p.name,
      p.ptn,
      p.class_name,
      round(avg(a.score))::integer as score,
      max(a.score)::integer as best_score,
      sum(a.correct_count)::integer as correct_count,
      sum(a.total_questions)::integer as total_questions,
      sum(a.duration_seconds)::integer as duration_seconds,
      count(*)::integer as attempts_count,
      max(a.submitted_at) as submitted_at
    from public.tryout_attempts a
    join public.profiles p on p.id = a.user_id
    where p_tryout_id is null
    group by a.user_id, p.name, p.ptn, p.class_name
  )
  select * from per_event
  union all
  select * from overall
  order by score desc, attempts_count desc, duration_seconds asc, submitted_at asc;
$$;


create or replace function public.complete_dummy_topup_order(p_order_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_uid uuid := auth.uid();
  v_order public.coin_topup_orders%rowtype;
  v_profile public.profiles%rowtype;
  v_new_balance integer;
begin
  if v_uid is null then
    raise exception 'Silakan login terlebih dahulu.';
  end if;

  select * into v_order
  from public.coin_topup_orders
  where id = p_order_id
    and user_id = v_uid
  for update;

  if not found then
    raise exception 'Tagihan top-up tidak ditemukan.';
  end if;

  if v_order.status = 'paid' then
    select coin_balance into v_new_balance
    from public.profiles
    where id = v_uid;

    return jsonb_build_object(
      'coin_balance', v_new_balance,
      'order', to_jsonb(v_order)
    );
  end if;

  if v_order.status <> 'pending' then
    raise exception 'Tagihan ini tidak lagi berstatus menunggu pembayaran.';
  end if;

  select * into v_profile
  from public.profiles
  where id = v_uid
  for update;

  v_new_balance := v_profile.coin_balance + v_order.coins;

  perform set_config('app.allow_wallet_mutation', 'on', true);

  update public.profiles
  set coin_balance = v_new_balance
  where id = v_uid;

  update public.coin_topup_orders
  set status = 'paid',
      paid_at = now()
  where id = v_order.id
  returning * into v_order;

  insert into public.coin_transactions (
    user_id,
    amount,
    type,
    title,
    reference_id,
    balance_after
  )
  values (
    v_uid,
    v_order.coins,
    'topup',
    'Top-Up ' || v_order.package_name || ' (' || v_order.payment_method || ')',
    v_order.order_code,
    v_new_balance
  );

  return jsonb_build_object(
    'coin_balance', v_new_balance,
    'order', to_jsonb(v_order)
  );
end;
$$;

